export const DICTIONARY: Map<string, WordEntry> = new Map();

RAW_DICTIONARY.forEach((item) => {
  const norm = normalizeWord(item.word);
  if (!DICTIONARY.has(norm)) {
    DICTIONARY.set(norm, {
      word: norm,
      category: item.category,
      vec: createVec(item.weights)
    });
  }
});

/**
 * Calculates cosine similarity between two 16-dim vectors.
 * Returns value between -1.0 and 1.0 (usually 0.0 to 1.0 for normalized semantic vectors).
 */
export function cosineSimilarity(vecA: number[], vecB: number[]): number {
  let dotProduct = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < vecA.length; i++) {
    dotProduct += vecA[i] * vecB[i];
    normA += vecA[i] * vecA[i];
    normB += vecB[i] * vecB[i];
  }
  if (normA === 0 || normB === 0) return 0;
  return dotProduct / (Math.sqrt(normA) * Math.sqrt(normB));
}

/**
 * Generates an estimated vector for words that might not be in our pre-indexed dictionary.
 * Uses letter trigram/stem heuristic so every Spanish word has a consistent vector.
 */
export function getWordVector(word: string): number[] {
  const norm = normalizeWord(word);
  const existing = DICTIONARY.get(norm);
  if (existing) return existing.vec;

  // Fallback: build a pseudo-vector based on character distribution and word length
  const vec = new Array(16).fill(0.1);
  let charSum = 0;
  for (let i = 0; i < norm.length; i++) {
    const code = norm.charCodeAt(i);
    charSum += code;
    const targetDim = (code * (i + 1)) % 16;
    vec[targetDim] += 0.3;
  }
  const lengthDim = norm.length % 16;
  vec[lengthDim] += 0.4;

  const mag = Math.sqrt(vec.reduce((sum, v) => sum + v * v, 0));
  return vec.map(v => (mag > 0 ? v / mag : 0));
}
