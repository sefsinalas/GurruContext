// Helper to construct normalized vector
function createVec(weights: Record<number, number>): number[] {
  const vec = new Array(16).fill(0.05);
  for (const [dimStr, val] of Object.entries(weights)) {
    const dim = parseInt(dimStr, 10);
    vec[dim] = val;
  }
  // Normalize vector to unit length
  const mag = Math.sqrt(vec.reduce((sum, v) => sum + v * v, 0));
  return vec.map(v => (mag > 0 ? v / mag : 0));
}

